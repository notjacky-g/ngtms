package com.hwacom.ngtms.cam.vo;

import com.google.gwt.user.client.rpc.IsSerializable;
import java.io.Serializable;

public class BrowserAlarmVO implements BrowserAlarmIF, Serializable, IsSerializable {

  private static final long serialVersionUID = 6761955058399686962L;
  public Long id;
  public String content;

  public BrowserAlarmVO() {}

  public BrowserAlarmVO(Long id, String content) {
    this.id = id;
    this.content = content;
  }

  public Long getId() {
    return id;
  }

  public void setId(Long id) {
    this.id = id;
  }

  public String getContent() {
    return content;
  }

  public void setContent(String content) {
    this.content = content;
  }

  @Override
  public String toString() {
    return "BrowserAlarmDTO [id=" + id + ", content=" + content + "]";
  }

  @Override
  public int hashCode() {
    final int prime = 31;
    int result = 1;
    result = prime * result + ((id == null) ? 0 : id.hashCode());
    return result;
  }

  @Override
  public boolean equals(Object obj) {
    if (this == obj) return true;
    if (obj == null) return false;
    if (getClass() != obj.getClass()) return false;
    BrowserAlarmVO other = (BrowserAlarmVO) obj;
    if (id == null) {
      if (other.id != null) return false;
    } else if (!id.equals(other.id)) return false;
    return true;
  }
}
