package com.hwacom.ngtms.ao.shared.dto;

import com.google.gwt.user.client.rpc.IsSerializable;
import java.io.Serializable;

/** @author bryan.lin */
public class CategoryDTO implements Serializable, IsSerializable {

  private static final long serialVersionUID = 8616835374724907257L;

  private String id;

  private String name;

  public CategoryDTO() {}

  public CategoryDTO(String id, String name) {
    this.id = id;
    this.name = name;
  }

  @Override
  public int hashCode() {
    int hash = 0;
    hash += (id != null ? id.hashCode() : 0);
    return hash;
  }

  @Override
  public boolean equals(Object object) {
    if (!(object instanceof CategoryDTO)) {
      return false;
    }
    CategoryDTO other = (CategoryDTO) object;
    if ((this.id == null && other.id != null) || (this.id != null && !this.id.equals(other.id))) {
      return false;
    }
    return true;
  }

  @Override
  public String toString() {
    return "CategoryDTO [id=" + id + ", " + "name=" + name + "]";
  }

  /** @return the id */
  public String getId() {
    return id;
  }

  /** @param id the id to set */
  public void setId(String id) {
    this.id = id;
  }

  /** @return the name */
  public String getName() {
    return name;
  }

  /** @param name the name to set */
  public void setName(String name) {
    this.name = name;
  }
}
